interface RgbEntry {
    name: string;
    rgb: [number, number, number];
}

function hexToRgb(hex: string): [number, number, number] {
    return [
        parseInt(hex.slice(1, 3), 16),
        parseInt(hex.slice(3, 5), 16),
        parseInt(hex.slice(5, 7), 16),
    ];
}

const RGB_TABLE: RgbEntry[] = TABLE.map(([name, hex]) => ({ name, rgb: hexToRgb(hex) }));

/** 离给定 RGB 最近的传统色名（加权欧氏距离，权重按人眼亮度敏感度）。 */
export function nearestTraditionalColor(r: number, g: number, b: number): string {
    let best = RGB_TABLE[0]!;
    let bestDist = Number.POSITIVE_INFINITY;
    for (const entry of RGB_TABLE) {
        const dr = r - entry.rgb[0];
        const dg = g - entry.rgb[1];
        const db = b - entry.rgb[2];
        const dist = 0.299 * dr * dr + 0.587 * dg * dg + 0.114 * db * db;
        if (dist < bestDist) {
            bestDist = dist;
            best = entry;
        }
    }
    return best.name;
}
